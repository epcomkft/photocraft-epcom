import { readFile, writeFile } from 'node:fs/promises';
const names = ['core.mjs', 'edge-colors.mjs', 'onnx-compat.mjs', 'worker-source.mjs'];
const parts = [];
for (const name of names) {
  const content = (await readFile(new URL(name, import.meta.url), 'utf8')).replace(/^import .+ from ['"].+['"];\s*$/gm, '').replace(/^export (?=(?:async )?function |const )/gm, '');
  if (/^\s*(import |export )/m.test(content)) throw new Error(`Unbundled syntax: ${name}`);
  parts.push(`// ${name}\n${content.trim()}`);
}
const output = '// Generated by build.mjs. No local ES-module dependencies.\n"use strict";\n' + parts.join('\n\n') + '\n';
const target = new URL('worker.js', import.meta.url);
if (process.argv.includes('--check')) {
  if (await readFile(target, 'utf8') !== output) throw new Error('Run node build.mjs: worker.js is stale.');
  console.log('Worker bundle matches sources.');
} else { await writeFile(target, output); console.log('Built worker.js.'); }
