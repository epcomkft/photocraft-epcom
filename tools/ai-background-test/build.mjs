// Dependency-free distribution build. Run after changing the source modules.
// The checked-in classic script needs no local ES-module/MIME support on the host.
import { readFile, writeFile } from 'node:fs/promises';
import { fileURLToPath } from 'node:url';
import { resolve, dirname } from 'node:path';
const root = dirname(fileURLToPath(import.meta.url));
const files = ['matting-core.mjs', 'matting-engine.mjs', 'edge-colors.mjs', 'app-source.mjs'];
const parts = [];
for (const name of files) {
  let code = await readFile(resolve(root, name), 'utf8');
  code = code.replace(/^import\s+[^\n]+\s+from\s+['"][^'"]+['"];\s*$/gm, '')
    .replace(/^export\s+(?=(?:async\s+)?function\b|const\b)/gm, '');
  if (/^\s*(?:import\s|export\s)/m.test(code)) throw new Error(`Unsupported static module syntax in ${name}`);
  parts.push(`// ---- ${name} ----\n${code.trim()}`);
}
const result = '// GENERATED by build.mjs. Edit the .mjs sources, then rebuild.\n' +
  '// PhotoCraft v6: single-file classic-script distribution.\n' +
  '(() => {\n"use strict";\n\n' + parts.join('\n\n') + '\n})();\n';
const target = resolve(root, 'app.js');
if (process.argv.includes('--check')) {
  if (await readFile(target, 'utf8') !== result) throw new Error('app.js is stale. Run node tools/ai-background-test/build.mjs');
  console.log('Distribution bundle matches its sources.');
} else {
  await writeFile(target, result);
  console.log('Built app.js; upload index.html, app.js and style.css.');
}
